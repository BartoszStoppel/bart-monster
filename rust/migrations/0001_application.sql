CREATE TABLE hub_achievement (
    id uuid NOT NULL,
    created_at timestamp with time zone NOT NULL,
    slug character varying(50) NOT NULL,
    title character varying(300) NOT NULL,
    description text NOT NULL,
    icon character varying(30) NOT NULL
);

CREATE TABLE hub_activity (
    user_id uuid NOT NULL,
    visit_count integer NOT NULL,
    total_seconds integer NOT NULL,
    last_seen_at timestamp with time zone NOT NULL,
    CONSTRAINT hub_activity_total_seconds_check CHECK ((total_seconds >= 0)),
    CONSTRAINT hub_activity_visit_count_check CHECK ((visit_count >= 0))
);

CREATE TABLE hub_award (
    id uuid NOT NULL,
    detail text NOT NULL,
    awarded_at timestamp with time zone NOT NULL,
    achievement_id uuid NOT NULL,
    user_id uuid NOT NULL
);

CREATE TABLE hub_bounty (
