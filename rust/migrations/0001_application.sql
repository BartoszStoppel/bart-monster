CREATE TABLE hub_usergame (
    id uuid NOT NULL,
    created_at timestamp with time zone NOT NULL,
    owned boolean NOT NULL,
    wishlist boolean NOT NULL,
    wishlist_priority smallint,
    wishlist_note text NOT NULL,
    collection_added_at timestamp with time zone,
    rating double precision,
    comment text NOT NULL,
    rating_created_at timestamp with time zone,
    rating_updated_at timestamp with time zone,
    tier character varying(1) NOT NULL,
    "position" integer NOT NULL,
    score double precision,
    tier_created_at timestamp with time zone,
    updated_at timestamp with time zone NOT NULL,
    legacy_ids jsonb NOT NULL,
    game_id integer NOT NULL,
