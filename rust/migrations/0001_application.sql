    difficulty_updated_at timestamp with time zone,
    CONSTRAINT hub_usergame_difficulty_position_check CHECK ((difficulty_position >= 0)),
    CONSTRAINT hub_usergame_difficulty_tier_check CHECK ((difficulty_tier >= 0)),
    CONSTRAINT hub_usergame_position_check CHECK (("position" >= 0)),
    CONSTRAINT hub_usergame_wishlist_priority_check CHECK ((wishlist_priority >= 0)),
    CONSTRAINT unranked_difficulty_state CHECK (((difficulty_tier IS NOT NULL) OR (difficulty_position = 0))),
    CONSTRAINT unranked_game_state CHECK (((NOT ((tier)::text = ''::text)) OR (("position" = 0) AND (score IS NULL)))),
    CONSTRAINT valid_difficulty_tier CHECK (((difficulty_tier IS NULL) OR ((difficulty_tier >= 1) AND (difficulty_tier <= 6)))),
    CONSTRAINT valid_game_rating CHECK (((rating IS NULL) OR ((rating >= (1.0)::double precision) AND (rating <= (10.0)::double precision)))),
    CONSTRAINT valid_game_score CHECK (((score IS NULL) OR ((score >= (1.0)::double precision) AND (score <= (10.0)::double precision)))),
    CONSTRAINT valid_game_tier CHECK (((tier)::text = ANY ((ARRAY[''::character varying, 'S'::character varying, 'A'::character varying, 'B'::character varying, 'C'::character varying, 'D'::character varying, 'F'::character varying])::text[]))),
    CONSTRAINT valid_wishlist_priority CHECK (((wishlist_priority IS NULL) OR ((wishlist_priority >= 1) AND (wishlist_priority <= 3))))
);

